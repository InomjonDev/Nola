-- Event-trigger procedures are invoked by PostgreSQL's event trigger manager;
-- they are not intended to be callable as RPCs by application roles.
revoke all on function public.rls_auto_enable() from public, anon, authenticated;

-- This table is an append-only abuse-control ledger. A surrogate key helps
-- maintenance and diagnostics while its rows remain inaccessible to clients.
alter table public.spending_parse_attempts
  add column id bigint generated by default as identity;
alter table public.spending_parse_attempts
  add constraint spending_parse_attempts_pkey primary key (id);

