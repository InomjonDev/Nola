export type TranslationKey = keyof typeof translations.en;

export function languageLocale(language: Language) {
  return language === "ru" ? "ru-RU" : language === "uz" ? "uz-Latn-UZ" : "en-US";
}

export function detectLanguage(locale = Intl.NumberFormat().resolvedOptions().locale): Language {
  const normalized = locale.toLowerCase();
  if (normalized.startsWith("ru")) return "ru";
  if (normalized.startsWith("uz")) return "uz";
  return "en";
}

export function createTranslator(language: Language) {
  return (key: TranslationKey) => translations[language][key] ?? translations.en[key];
}
